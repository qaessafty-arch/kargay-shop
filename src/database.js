/** Turns the app's `?` placeholders into Postgres `$1, $2, …`. The app never puts `?` inside SQL text. */
function numbered(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

/**
 * Thin wrapper over a Postgres client (pg Pool/Client, or PGlite in tests).
 * All methods are async; the schema is created the first time the database is used.
 */
export class Database {
  constructor(driver) {
    this.driver = driver;
    this.readyPromise = null;
  }

  /**
   * Resolves once the schema exists. If setup fails (for example while a serverless database is waking up),
   * the failure is not cached: the next call tries again instead of failing forever on this server instance.
   */
  get ready() {
    if (!this.readyPromise) {
      this.readyPromise = this.migrate().catch((error) => {
        this.readyPromise = null;
        throw error;
      });
    }
    return this.readyPromise;
  }

  async migrate() {
    // Several serverless instances can start at once. CREATE TABLE IF NOT EXISTS is not safe to run
    // concurrently in Postgres, so one transaction-scoped advisory lock lets only one instance run it at a time.
    const client = this.driver.connect ? await this.driver.connect() : this.driver;
    try {
      await client.query('BEGIN');
      await client.query('SELECT pg_advisory_xact_lock(724519)');
      for (const statement of SCHEMA) {
        await client.query(statement);
      }
      const now = Date.now();
      for (const [key, value] of Object.entries(config.shopDefaults)) {
        await client.query('INSERT INTO settings (key, value, updated_at) VALUES ($1, $2, $3) ON CONFLICT (key) DO NOTHING', [key, value, now]);
      }
      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally {
      if (client !== this.driver) client.release();
    }
  }

  async all(sql, params = []) {
    await this.ready;
    return (await this.driver.query(numbered(sql), params)).rows;
  }

  async get(sql, params = []) {
    await this.ready;
    return (await this.driver.query(numbered(sql), params)).rows[0];
  }

  /** Returns { changes, id } for INSERT/UPDATE/DELETE. Use `RETURNING id` in SQL to get the new id. */
  async run(sql, params = []) {
    await this.ready;
    const result = await this.driver.query(numbered(sql), params);
    const id = result.rows?.[0]?.id;
    return { changes: result.affectedRows ?? result.rowCount ?? 0, id };
  }

  /** Runs fn with a transaction-scoped Database. Commits if fn resolves, rolls back if it throws. */
  async transaction(fn) {
    await this.ready;
    // A pool hands out a different connection per query, so a transaction must hold one client for its whole run.
    const client = this.driver.connect ? await this.driver.connect() : this.driver;
    const scoped = new TxDatabase(client);
    await client.query('BEGIN');
    try {
      const result = await fn(scoped);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally {
      if (client !== this.driver) client.release();
    }
  }

  async close() {
    await this.driver.end?.();
  }
}

class TxDatabase {
  constructor(driver) {
    this.driver = driver;
  }
  async all(sql, params = []) {
    return (await this.driver.query(numbered(sql), params)).rows;
  }
  async get(sql, params = []) {
    return (await this.driver.query(numbered(sql), params)).rows[0];
  }
  async run(sql, params = []) {
    const result = await this.driver.query(numbered(sql), params);
    return { changes: result.affectedRows ?? result.rowCount ?? 0, id: result.rows?.[0]?.id };
  }
}

let shared = null;

/**
 * The app's database. On Vercel and in production it is Neon Postgres (DATABASE_URL).
 * Local development without DATABASE_URL uses an embedded Postgres stored in data/pglite.
 */
export function getDatabase() {
  if (!shared) {
    shared = new Database(createDriver());
  }
  return shared;
}

function createDriver() {
  if (config.databaseUrl) {
    const pool = new pg.Pool({
      connectionString: config.databaseUrl,
      max: 5,
      idleTimeoutMillis: 10_000,
      connectionTimeoutMillis: 10_000,
      keepAlive: true,
    });
    // An idle connection dropped by the database must not crash the process.
    pool.on('error', (error) => console.error('[db pool]', error.message));
    return pool;
  }
  if (config.isProduction) {
    throw new Error('DATABASE_URL is not set. Add your Neon connection string to the environment.');
  }
  return localPostgres(config.localDatabaseDir);
}

/** Embedded Postgres for local development only. Same SQL as production. */
export async function localPostgresDriver(dir) {
  const { PGlite } = await import('@electric-sql/pglite');
  return new PGlite(dir);
}

function localPostgres(dir) {
  // PGlite is loaded lazily so production builds never need it.
  let instance = null;
  const get = async () => {
    if (!instance) instance = await localPostgresDriver(dir);
    return instance;
  };
  return {
    async query(sql, params) {
      const db = await get();
      return db.query(sql, params);
    },
    async end() {
      if (instance) await instance.close();
    },
  };
}
